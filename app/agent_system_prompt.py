def disclosure_note(categories):
    """One line per tool category the turn may load (names only; the definitions come with load_tools)."""
    lines=['工具按类别按需加载：下面是可加载的类别，用 load_tools(categories) 一次加载本题需要的全部类别，定义在下一步起生效；已经带上的工具不必再加载。']
    lines+=[f'- {info.name}：{info.summary}' for info in categories]
    return '\n'.join(lines)
