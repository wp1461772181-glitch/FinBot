// Brand mark generator: samples one still frame of the bloub engine (idle, t = 1 s, circle) and writes it as SVG, the way bloub
// makes its own favicon (jeremy-prt/bloub docs/measurements.md, "The favicon is not an approximation"): the circle (r = RAYON) and both
// eye matrices are exactly what `engine.sample(1)` returns, eyes are holes in a mask.
//
//   cd frontend && bun scripts/brand/gen-brand-logo.ts          # rewrites public/{favicon,logo,logo-lockup}.svg
//
// favicon.png (64) and apple-touch-icon.png (180, on a paper plate) are rasterised from these SVGs with @resvg/resvg-js
// (not a project dependency; installed in a scratch dir) — see scripts/brand/rasterize.mjs.
import { writeFileSync } from "node:fs";
import { BotEngine } from "../../src/bloub/engine";
import { RAYON } from "../../src/bloub/repere";

const GREEN = "#3ecf8e"; // bloub's `vert`, the FinBot green
const frame = new BotEngine(RAYON, "idle").sample(1);
const r = (n: number) => String(Math.round(n * 100) / 100);
const eyes = frame.eyes.map(e => `<path d="${e.d}" transform="${e.matrix}"${e.alpha !== 1 ? ` opacity="${r(e.alpha)}"` : ""} />`).join("\n    ");
const mask = (id: string) => `<mask id="${id}">
    <circle r="${RAYON}" fill="#fff" />
    <g fill="#000">
    ${eyes}
    </g>
  </mask>`;
const note = `<!-- Generated by scripts/brand/gen-brand-logo.ts: bloub engine (b4bb3c1, MIT) idle @ t=1 — perfect circle r=100 and both eye matrices as sampled. Eyes are holes. -->`;
const VB = "-108 -108 216 216";

// Tab icon: ink body, inverted on a dark tab bar (as bloub's own favicon).
writeFileSync("public/favicon.svg", `${note}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VB}">
  <style>.corps{fill:#0a0a0c}@media (prefers-color-scheme:dark){.corps{fill:#f9f9f9}}</style>
  ${mask("yeux")}
  <rect x="-108" y="-108" width="216" height="216" class="corps" mask="url(#yeux)" />
</svg>
`);

// In-app mark and README logo: the same frame in FinBot green (readable on both themes).
const body = (id: string, fill: string) => `${mask(id)}
  <rect x="-108" y="-108" width="216" height="216" fill="${fill}" mask="url(#${id})" />`;
writeFileSync("public/logo.svg", `${note}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VB}" role="img" aria-label="FinBot">
  <title>FinBot</title>
  ${body("yeux", GREEN)}
</svg>
`);

// Lockup: the mark + the FinBot wordmark (unchanged from the previous lockup).
writeFileSync("public/logo-lockup.svg", `${note}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 420 140" role="img" aria-label="FinBot">
  <title>FinBot</title>
  <g transform="translate(70 70) scale(0.62)">
  ${body("yeux", GREEN)}
  </g>
  <g transform="translate(176, 76)">
    <text x="0" y="0" font-family="-apple-system, BlinkMacSystemFont, 'Inter', sans-serif" font-size="48" font-weight="800" fill="#18181b" letter-spacing="-1.5">Fin<tspan fill="#fbbf24">Bot</tspan></text>
    <text x="2" y="26" font-family="ui-monospace, SFMono-Regular, Menlo, monospace" font-size="13" font-weight="600" fill="#71717a" letter-spacing="1.5">PERSONAL EQUITY RESEARCH</text>
  </g>
</svg>
`);
